import React, {
  useEffect,
  useMemo,
  CSSProperties,
  SVGAttributes,
  useRef,
  useState,
} from 'react'
import {
  useGG,
  themeState,
  focusNodes,
  unfocusNodes,
  EventArea,
  defineGroupAccessor,
  usePageVisibility,
} from '@graphique/graphique'
import { useAtom } from 'jotai'
import { NodeGroup } from 'react-move'
import { easeCubic } from 'd3-ease'
import { interpolate } from 'd3-interpolate'
import { scaleBand } from 'd3-scale'
import { Tooltip } from './tooltip'
import { Entrance, type GeomAes } from './types'

export interface GeomProps<Datum> {
  /**
   * **data used by this Geom**
   *
   * This will overwrite top-level `data` passed to `GG` as it relates to mappings defined in `aes`.
   */
  data?: Datum[]
  /**
   * **functional mapping applied to `data` for this Geom**
   *
   * This extends the top-level `aes` passed to `GG`. Any repeated mappings defined here will take precedence within the Geom.
   */
  aes?: GeomAes<Datum>
  /** attributes passed to the underlying SVG elements */
  attr?: SVGAttributes<SVGRectElement>
  /** should this Geom have a tooltip associated with it (_default_: `true`) */
  showTooltip?: boolean
  /** where elements should start as they enter the drawing area (_default_: `Entrance.DATA`) */
  entrance?: Entrance
  /** padding value (0-1) that sets the space between tile columns (_default_: `0`) */
  xPadding?: number
  /** padding value (0-1) that sets the space between tile rows (_default_: `0`) */
  yPadding?: number
  /** input x domain to use with continuous x scales (unique, sequential values across `[min, max]`).
   * For example, if a column represents a day, `xDomain` should include the full sequence of days between the min and max values. */
  xDomain?: (number | Date)[]
  /** input y domain to use with continuous y scales (unique, sequential values across `[min, max]`).
   * For example, if a row represents a day, `yDomain` should include the full sequence of days between the min and max values. */
  yDomain?: (number | Date)[]
  /** array of keys (of the kind that are generated by `aes.key`) used to programmatically focus associated tiles */
  focusedKeys?: string[]
  /** styles applied to focused elements */
  focusedStyle?: CSSProperties
  /** styles applied to unfocused elements */
  unfocusedStyle?: CSSProperties
  /** callback called for mousemove events on the drawing area when focusing data */
  onDatumFocus?: (data: Datum[], index: number[]) => void
  /** callback called for click events on the drawing area when selecting focused data */
  onDatumSelection?: (data: Datum[], index: number[]) => void
  /** callback called for mouseleave events on the drawing area */
  onExit?: () => void
}

const GeomTile = <Datum,>({
  data: localData,
  aes: localAes,
  attr,
  showTooltip = true,
  entrance = Entrance.DATA,
  xPadding = 0,
  yPadding = 0,
  xDomain,
  yDomain,
  focusedKeys,
  focusedStyle,
  unfocusedStyle,
  onDatumFocus,
  onDatumSelection,
  onExit,
}: GeomProps<Datum>) => {
  const { ggState } = useGG<Datum>() || {}
  const { data, aes, scales, copiedScales, height, width, margin } =
    ggState || {}

  const geomAes = useMemo(() => {
    if (localAes) {
      return {
        ...aes,
        ...localAes,
      }
    }
    return aes
  }, [aes, localAes])

  const [theme, setTheme] = useAtom(themeState)

  const isVisible = usePageVisibility()

  const baseAttr: SVGAttributes<SVGRectElement> = {
    fillOpacity: 1,
    strokeOpacity: 1,
  }

  const geomAttr: SVGAttributes<SVGRectElement> = {
    ...baseAttr,
    ...attr,
  }

  const { defaultFill, animationDuration: duration } = theme

  const [firstRender, setFirstRender] = useState(true)
  useEffect(() => {
    const timeout = setTimeout(() => setFirstRender(false), 0)
    return () => clearTimeout(timeout)
  }, [])

  const baseStyles: CSSProperties = {
    transition: 'fill-opacity 200ms',
    fillOpacity: geomAttr.fillOpacity,
    strokeOpacity: geomAttr.strokeOpacity,
    ...geomAttr.style,
  }

  const focusedStyles: CSSProperties = {
    ...baseStyles,
    ...focusedStyle,
  }

  const unfocusedStyles: CSSProperties = {
    ...baseStyles,
    fillOpacity: 0.5,
    strokeOpacity: 0.5,
    ...unfocusedStyle,
  }

  useEffect(() => {
    setTheme((prev) => ({
      ...prev,
      geoms: {
        ...prev.geoms,
        tile: {
          fillOpacity: geomAttr.style?.fillOpacity || geomAttr.fillOpacity,
          unfocusedStyles,
          stroke: geomAttr.stroke,
          strokeWidth: geomAttr.style?.strokeWidth || geomAttr.strokeWidth,
          strokeOpacity:
            geomAttr.style?.strokeOpacity || geomAttr.strokeOpacity,
          aes: geomAes,
        },
      },
    }))
  }, [attr, setTheme, geomAes])

  const fill = useMemo(
    () => (d: Datum) => {
      if (attr?.fill) return attr.fill

      return geomAes?.fill && copiedScales?.fillScale
        ? (copiedScales.fillScale(geomAes.fill(d)) as string | undefined)
        : defaultFill
    },
    [geomAes, copiedScales, attr, defaultFill],
  )

  const stroke = useMemo(
    () => (d: Datum) =>
      attr?.stroke ||
      (geomAes?.stroke && copiedScales?.strokeScale
        ? (copiedScales.strokeScale(geomAes.stroke(d) as any) as
            | string
            | undefined)
        : 'none'),
    [geomAes, copiedScales, attr],
  )

  const validFocusedKeys = useMemo(
    () => focusedKeys?.filter((v) => v),
    [focusedKeys],
  )

  const geomData = (localData || data).filter((d) => {
    const hasMissingFillValue =
      geomAes.fill &&
      (geomAes.fill(d) === null || typeof geomAes.fill(d) === 'undefined')
    const hasMissingXValue =
      geomAes.x &&
      (geomAes.x(d) === null || typeof geomAes.x(d) === 'undefined')
    const hasMissingYValue =
      geomAes.y &&
      (geomAes.y(d) === null || typeof geomAes.y(d) === 'undefined')

    return !hasMissingFillValue && !hasMissingXValue && !hasMissingYValue
  })

  const xBandScale = useMemo(() => {
    if (margin && width) {
      if (typeof scales?.xScale.bandwidth !== 'undefined') {
        return scales.xScale.paddingInner(xPadding)
      }
      const uniqueXs = Array.from(new Set(geomData?.map((d) => geomAes?.x(d))))
      return scaleBand()
        .range([margin.left, width - margin.right])
        .domain((xDomain || uniqueXs) as string[])
        .paddingInner(xPadding)
    }
    return null
  }, [geomData, geomAes, width, scales, margin, xPadding, xDomain])

  const yBandScale = useMemo(() => {
    if (margin && height) {
      if (typeof scales?.yScale.bandwidth !== 'undefined') {
        return scales.yScale.paddingInner(yPadding)
      }
      const uniqueYs = Array.from(
        new Set(geomData?.map((d) => geomAes?.y && geomAes.y(d))),
      )
      return scaleBand()
        .range([margin.bottom, height - margin.top])
        .domain((yDomain || uniqueYs) as string[])
        .paddingInner(yPadding)
    }
    return null
  }, [geomData, geomAes, height, scales, margin, yPadding, yDomain])

  const x = useMemo(() => {
    if (!scales?.xScale.bandwidth && margin && width && xBandScale) {
      scales?.xScale.range([
        margin.left + xBandScale.bandwidth() / 2,
        width - margin.right - xBandScale.bandwidth() / 2 - 0.5,
      ])
      return (d: Datum) =>
        (scales?.xScale(geomAes?.x(d)) || 0) - xBandScale.bandwidth() / 2 + 0.5
    }
    return (d: Datum) => scales?.xScale && scales.xScale(geomAes?.x(d))
  }, [scales, geomAes, xBandScale, margin, width])

  const y = useMemo(() => {
    if (!scales?.yScale.bandwidth && margin && height && yBandScale) {
      scales?.yScale.range([
        height - margin.bottom - yBandScale.bandwidth() / 2 - 0.5,
        margin.top + yBandScale.bandwidth() / 2,
      ])
      return (d: Datum) =>
        (scales?.yScale(geomAes?.y && geomAes.y(d)) || 0) -
        yBandScale.bandwidth() / 2 +
        0.5
    }
    return (d: Datum) =>
      scales?.yScale && geomAes?.y && scales.yScale(geomAes.y(d))
  }, [scales, geomAes, margin, height, yBandScale])

  const group = useMemo(
    () =>
      geomAes?.group || geomAes?.fill || geomAes?.stroke
        ? defineGroupAccessor(geomAes, true)
        : scales?.groupAccessor,
    [geomAes, defineGroupAccessor],
  )

  const keyAccessor = useMemo(
    () => (d: Datum) =>
      (geomAes?.key
        ? geomAes.key(d)
        : geomAes?.y && `${geomAes?.x(d)}-${geomAes?.y(d)}`) as string,
    [geomAes, scales],
  )

  const groupRef = useRef<SVGGElement>(null)
  const rects = groupRef.current?.getElementsByTagName('rect')

  return xBandScale && yBandScale ? (
    <>
      <g ref={groupRef}>
        {!firstRender && isVisible && (
          <NodeGroup
            data={[...geomData]}
            keyAccessor={keyAccessor}
            start={(d) => ({
              x: entrance === 'left' ? margin?.left : x(d),
              y: y(d) || 0,
              fill: 'transparent',
              stroke: 'transparent',
              fillOpacity: 0,
              strokeOpacity: 0,
            })}
            enter={(d) => ({
              x: [typeof x(d) === 'undefined' ? margin?.left : x(d)],
              y: [y(d) || 0],
              fill: [fill(d)],
              stroke: [stroke(d)],
              fillOpacity: [geomAttr.fillOpacity],
              strokeOpacity: [geomAttr.strokeOpacity],
              timing: { duration, ease: easeCubic },
            })}
            update={(d) => ({
              x: [typeof x(d) === 'undefined' ? margin?.left : x(d)],
              y: [typeof y(d) === 'undefined' ? height - margin?.bottom : y(d)],
              fill: firstRender ? fill(d) : [fill(d)],
              stroke: firstRender ? stroke(d) : [stroke(d)],
              fillOpacity: [geomAttr.fillOpacity],
              strokeOpacity: [geomAttr.strokeOpacity],
              timing: { duration, ease: easeCubic },
            })}
            leave={() => ({
              fill: ['transparent'],
              stroke: ['transparent'],
              y: [height - margin?.bottom],
              timing: { duration, ease: easeCubic },
            })}
            interpolation={(begVal, endVal) => interpolate(begVal, endVal)}
          >
            {(nodes) => (
              <>
                {nodes.map(({ state, key }) => {
                  let styles = {}
                  if (validFocusedKeys?.includes(key)) styles = focusedStyles
                  if (validFocusedKeys && !validFocusedKeys?.includes(key))
                    styles = unfocusedStyles
                  return (
                    <rect
                      key={key}
                      // eslint-disable-next-line react/jsx-props-no-spreading
                      {...attr}
                      fill={state.fill}
                      stroke={state.stroke}
                      x={state.x}
                      y={state.y}
                      width={xBandScale.bandwidth()}
                      height={yBandScale.bandwidth()}
                      fillOpacity={state.fillOpacity}
                      strokeOpacity={state.strokeOpacity}
                      style={{
                        pointerEvents: 'none',
                        ...baseStyles,
                        ...styles,
                      }}
                      data-testid="__gg_geom_tile"
                    />
                  )
                })}
              </>
            )}
          </NodeGroup>
        )}
      </g>
      {geomAes && group && showTooltip && (
        <>
          <EventArea
            x={x}
            y={y}
            data={geomData}
            aes={geomAes}
            xAdj={xBandScale.bandwidth() / 2}
            yAdj={yBandScale.bandwidth() / 2}
            onDatumFocus={onDatumFocus}
            onMouseOver={({ i }: { d: Datum[]; i: number[] }) => {
              const focusedIndexes = geomData.flatMap((gd, fi) =>
                validFocusedKeys?.includes(keyAccessor(gd)) ? fi : [],
              )

              if (rects) {
                focusNodes({
                  nodes: rects,
                  focusedIndex: [...focusedIndexes, ...[i].flat()],
                  focusedStyles,
                  unfocusedStyles,
                })
              }
            }}
            onClick={
              onDatumSelection
                ? ({ d, i }: { d: Datum[]; i: number[] }) => {
                    onDatumSelection(d, i)
                  }
                : undefined
            }
            onMouseLeave={() => {
              if (rects) {
                unfocusNodes({ nodes: rects, baseStyles })
                if (validFocusedKeys) {
                  focusNodes({
                    nodes: rects,
                    focusedIndex: geomData.flatMap((d, i) =>
                      validFocusedKeys?.includes(keyAccessor(d)) ? i : [],
                    ),
                    focusedStyles,
                    unfocusedStyles,
                  })
                }
              }

              if (onExit) onExit()
            }}
          />
          <Tooltip
            x={x}
            y={y}
            xAdj={xBandScale.bandwidth() / 2}
            yAdj={yBandScale.bandwidth() / 2}
            group={group}
            aes={geomAes}
          />
        </>
      )}
    </>
  ) : null
}

GeomTile.displayName = 'GeomTile'
export { GeomTile }
